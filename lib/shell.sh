# shellcheck shell=bash
# Shell profile: build ~/.docks_profile from shell/ and source it from the rc
# files of this OS. The profile is a copy, not a link to the repository, so it
# keeps working when the clone moves. A changed repository profile replaces
# the copy on the next run. The copy gets no backup: the repository is its source.

SHELL_PROFILE_NAME='.docks_profile'
SHELL_OS_MARKER='# @os-profile@'
SHELL_BLOCK_BEGIN='# >>> docks profile >>>'
SHELL_BLOCK_END='# <<< docks profile <<<'
SHELL_DUPLICATE_VARS='NVM_DIR PNPM_HOME BUN_INSTALL DOCKER_HOST ANDROID_HOME'

shell_profile_path() {
  printf '%s/%s\n' "$USER_HOME" "$SHELL_PROFILE_NAME"
}

# The OS part of the profile in this repository.
shell_os_part() {
  case "$PLATFORM_OS" in
    ubuntu) printf '%s/shell/profile.linux.sh\n' "$REPO_ROOT" ;;
    macos) printf '%s/shell/profile.macos.sh\n' "$REPO_ROOT" ;;
    *) die "unknown platform: $PLATFORM_OS" ;;
  esac
}

# Print one profile part without its shellcheck directive line.
shell_print_part() {
  local line

  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      '# shellcheck shell='*) ;;
      *) printf '%s\n' "$line" ;;
    esac
  done <"$1"
}

# Print the content of ~/.docks_profile: shell/profile.sh with the OS part in
# place of the @os-profile@ line.
shell_profile_render() {
  local line os_part

  os_part="$(shell_os_part)"
  printf '# ~/%s: generated by the dotfiles installer (%s).\n' "$SHELL_PROFILE_NAME" "$PLATFORM_OS"
  printf '# Source: shell/profile.sh and shell/%s in the dotfiles repository.\n' "${os_part##*/}"
  printf '# Do not edit this file: ./install.sh shell replaces a changed copy.\n'
  while IFS= read -r line || [ -n "$line" ]; do
    case "$line" in
      '# shellcheck shell='*) ;;
      "$SHELL_OS_MARKER") shell_print_part "$os_part" ;;
      *) printf '%s\n' "$line" ;;
    esac
  done <"$REPO_ROOT/shell/profile.sh"
}

# Write ~/.docks_profile when it is missing or differs from the repository.
shell_install_profile_file() {
  local target id label staged existed=0

  target="$(shell_profile_path)"
  id="shell:$SHELL_PROFILE_NAME"
  label="Shell profile $target"
  defer_step "$label"
  if [ -f "$target" ] && shell_profile_render | cmp -s - "$target"; then
    quiet_add "$SHELL_PROFILE_NAME"
    record_result "$id" "$label" present -
    return 0
  fi
  out_flush
  if [ -e "$target" ]; then
    existed=1
  fi
  if [ "$DRY_RUN" = 1 ]; then
    printf '[dry-run] write %s from shell/profile.sh and shell/%s\n' "$target" "$(basename "$(shell_os_part)")"
    record_result "$id" "$label" planned -
    return 0
  fi
  staged="$(cache_file docks_profile)"
  if ! mkdir -p "$CACHE_DIR" || ! shell_profile_render >"$staged"; then
    record_result "$id" "$label" failed - 'cannot build the profile'
    return 1
  fi
  # ~/.docks_profile is generated from the repository, so the repository is
  # its backup. A replaced copy needs no timestamp copy.
  if ! install -m 0644 "$staged" "$target"; then
    record_result "$id" "$label" failed - 'cannot write the profile'
    return 1
  fi
  if [ "$existed" = 1 ]; then
    log_status installed 'Updated.'
    record_result "$id" "$label" installed - updated
  else
    log_status installed 'Installed.'
    record_result "$id" "$label" installed -
  fi
}

# Print the rc block (with a leading blank line).
shell_profile_block() {
  printf '\n%s\n' "$SHELL_BLOCK_BEGIN"
  printf '# Added by the dotfiles installer. Delete this block to unlink ~/%s.\n' "$SHELL_PROFILE_NAME"
  cat <<EOF
if [ -r "\$HOME/$SHELL_PROFILE_NAME" ]; then
  . "\$HOME/$SHELL_PROFILE_NAME"
fi
EOF
  printf '%s\n' "$SHELL_BLOCK_END"
}

# True when the rc file contains the begin marker.
shell_rc_has_block() {
  local rc="$1"
  [ -f "$rc" ] && grep -qF -- "$SHELL_BLOCK_BEGIN" "$rc"
}

# Print the rc file without the docks profile block.
shell_rc_outside_block() {
  local rc="$1"
  awk -v begin="$SHELL_BLOCK_BEGIN" -v end="$SHELL_BLOCK_END" '
    $0 == begin { skip = 1 }
    !skip { print }
    $0 == end { skip = 0 }
  ' "$rc"
}

# Warn about variables that the rc file sets outside the block.
# The profile sets them, so the user should remove the manual copies.
shell_warn_duplicates() {
  local rc="$1" outside var
  [ -r "$rc" ] || return 0
  outside="$(shell_rc_outside_block "$rc")" || return 0
  for var in $SHELL_DUPLICATE_VARS; do
    if printf '%s\n' "$outside" | grep -Eq "^[[:space:]]*(export[[:space:]]+)?${var}="; then
      warn "$rc sets $var outside the docks profile block. ~/$SHELL_PROFILE_NAME sets it too; remove the manual line."
    fi
  done
  return 0
}

# Append the block to the rc file (create the file when it is missing).
shell_append_block() {
  local rc="$1" block prefix=''
  block="$(shell_profile_block)"
  if [ "$DRY_RUN" = 1 ]; then
    printf '[dry-run] append to %s:\n%s\n' "$rc" "$block"
    return 0
  fi
  # Terminate an unterminated last line before the block.
  if [ -s "$rc" ] && [ -n "$(tail -c 1 "$rc")" ]; then
    prefix=$'\n'
  fi
  printf '%s%s\n' "$prefix" "$block" >> "$rc" || return 1
}

# Wire one rc file and record the result as shell:<basename>.
shell_wire_rc() {
  local rc="$1" id label
  id="shell:$(basename "$rc")"
  label="Shell rc $rc"
  defer_step "$label"
  shell_warn_duplicates "$rc"
  if shell_rc_has_block "$rc"; then
    quiet_add "$(basename "$rc")"
    record_result "$id" "$label" present -
    return 0
  fi
  out_flush
  if [ -e "$rc" ] && { [ ! -f "$rc" ] || [ ! -r "$rc" ] || [ ! -w "$rc" ]; }; then
    record_result "$id" "$label" failed - "not a readable and writable file"
    return 1
  fi
  if [ -e "$rc" ] && ! backup_file "$rc"; then
    record_result "$id" "$label" failed - "backup failed"
    return 1
  fi
  if ! shell_append_block "$rc"; then
    record_result "$id" "$label" failed - "append failed"
    return 1
  fi
  if [ "$DRY_RUN" = 1 ]; then
    record_result "$id" "$label" planned -
  else
    log_status installed 'Installed.'
    record_result "$id" "$label" installed -
  fi
}

# Write ~/.docks_profile, then source it from every rc file of this OS.
install_shell_profile() {
  local rc_list rc
  local rc_files=()

  # A failure is recorded; the rc block only sources a readable profile.
  shell_install_profile_file || true
  rc_list="$(os_rc_files)" || die "os_rc_files failed"
  while IFS= read -r rc; do
    [ -n "$rc" ] && rc_files+=("$rc")
  done <<< "$rc_list"
  for rc in ${rc_files[@]+"${rc_files[@]}"}; do
    # Failures are recorded; continue with the next rc file.
    shell_wire_rc "$rc" || true
  done
  return 0
}
